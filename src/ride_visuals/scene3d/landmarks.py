def _from_above(half: Stroke) -> tuple[Stroke, ...]:
    """A plan view from one half of it (nose at x=0 to tail, z >= 0), mirrored about the axis."""
    return ((*half, *((x, -z) for x, z in reversed(half[:-1]))),)


